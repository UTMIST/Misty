"""Durable post-meeting work. All network and storage collaborators are injected."""

from datetime import datetime, timedelta, timezone
from hashlib import sha256
from html import escape
import json
import logging
from uuid import uuid4
from zoneinfo import ZoneInfo

from contracts.directory import DirectoryUnavailable
from contracts.meeting import MeetingRecord, MeetingRetryResult, WriterError
from src.indexing import index_doc
from src.source_access import resolve_google_permissions, source_grant_expiry

logger = logging.getLogger("documentation_system.audit")
TERMINAL = {"failed", "saved", "inaccessible", "removing", "removed"}


def payload_digest(payload):
    return sha256(
        json.dumps(payload.model_dump(mode="json"), sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()


def render_html(record):
    """Escape every supplied character; transcript order and spacing are preserved."""

    def e(value):
        return escape(str(value))

    def items(values):
        return "<ul>" + "".join(f"<li>{e(v)}</li>" for v in values) + "</ul>"

    zone = ZoneInfo("America/Toronto")
    return (
        f"<html><body><h1>{e(record.title)}</h1>"
        f"<p>Text channel: {e(record.text_channel_id)}; voice channel: {e(record.voice_channel_id)}</p>"
        f"<p>Started: {e(record.started_at.astimezone(zone).isoformat())}; "
        f"ended: {e(record.ended_at.astimezone(zone).isoformat())}</p>"
        f"<p>Requester: {e(record.requester_person_id or record.requester_discord_id)}</p>"
        f"<p>Teams: {e(', '.join(map(str, record.audience_team_ids)) or 'admins only')}</p>"
        "<h2>Participants</h2>"
        + items(
            f"{p['display_name']} (directory: {p['person_id']})"
            if p.get("person_id")
            else f"{p['display_name']} (Discord: {p['discord_id']})"
            for p in record.participants
        )
        + f"<h2>Minutes</h2><p>{e(record.summary)}</p><h2>Decisions</h2>"
        + items(record.decisions)
        + "<h2>Action items</h2>"
        + items(record.action_items)
        + f"<h2>Full transcript</h2><pre>{e(record.pending_payload['transcript'])}</pre>"
        + f"<p>Generated by Misty on {e(record.generated_at.isoformat())}. "
        f"Meeting ID {e(record.meeting_id)}. To request removal, contact a Misty admin with this link.</p>"
        "</body></html>"
    )


class MeetingRecords:
    def __init__(self, storage, writer, directory, settings, *, embedder=None, now=None):
        self.storage = storage
        self.writer = writer
        self.directory = directory
        self.settings = settings
        self.embedder = embedder
        self.now = now or (lambda: datetime.now(timezone.utc))

    def accept(self, meeting_id, payload, *, actor):
        existing = self.storage.get_meeting(meeting_id)
        digest = payload_digest(payload)
        if existing:
            if existing.payload_hash != digest:
                raise ValueError("meeting payload conflict")
            return existing, False
        # Resolve authorization and destination audience before any Google writes.
        # An unavailable directory prevents acceptance (the meeting service holds
        # and retries); an unconfigured/unsynced audience is explicitly admin-only.
        audience = self.directory.get_meeting_audience(payload.guild_id, payload.voice_channel_id)
        participants = []
        for participant in payload.participants:
            try:
                person_id = self.directory.get_person_id_by_discord(participant.discord_id)
            except DirectoryUnavailable:
                person_id = None
            participants.append(
                participant.model_dump() | {"person_id": str(person_id) if person_id else None}
            )
        try:
            requester = self.directory.get_person_id_by_discord(payload.requester_discord_id)
        except DirectoryUnavailable:
            requester = None
        now = self.now()
        fields = payload.model_dump(exclude={"transcript", "participants"})
        record = MeetingRecord(
            meeting_id=meeting_id,
            payload_hash=digest,
            **fields,
            participants=participants,
            requester_person_id=requester,
            audience_team_ids=sorted(audience),
            audience_group_emails=sorted(audience.values()),
            generated_at=now,
            pending_payload={"transcript": payload.transcript},
            next_attempt_at=now,
            created_at=now,
            updated_at=now,
            created_by=actor,
            updated_by=actor,
        )
        return self.storage.put_meeting(record)

    def _change(self, record, *, live_at=None, **values):
        return self.storage.change_meeting(record, values, actor="meeting-records", live_at=live_at)

    def _owns(self, record):
        current = self.storage.get_meeting(record.meeting_id)
        return (
            current is not None
            and current.version == record.version
            and current.create_attempt_id == record.create_attempt_id
            and current.create_lease_until is not None
            and current.create_lease_until > self.now()
            and not current.removed_at
        )

    def _adopt(self, record, document_id):
        if (
            not self._owns(record)
            or record.google_document_id
            or document_id in record.google_deletions
        ):
            return None
        return self._change(
            record,
            live_at=self.now(),
            google_document_id=document_id,
            doc_url=f"https://docs.google.com/document/d/{document_id}/edit",
            persistence_status="doc_created",
            pending_payload=None,
            last_error=None,
        )

    def _failure(self, record, exc, *, creating=False):
        if not self._owns(record):
            return
        uncertain = creating and exc.uncertain
        failed = record.attempts >= self.settings.meeting_record_max_attempts
        status = (
            "create_uncertain"
            if uncertain
            else "failed"
            if failed
            else ("pending" if creating else record.persistence_status)
        )
        self._change(
            record,
            live_at=self.now(),
            persistence_status=status,
            last_error=exc.code,
            failed_at=self.now() if status == "failed" else record.failed_at,
            next_attempt_at=record.create_lease_until
            if uncertain
            else self.now() + timedelta(seconds=min(3600, 30 * 2 ** min(record.attempts, 7))),
            create_lease_until=record.create_lease_until if uncertain else None,
        )
        logger.warning(
            "meeting.record_retry meeting_id=%s status=%s attempts=%s code=%s",
            record.meeting_id,
            status,
            record.attempts,
            exc.code,
        )

    def _index(self, record):
        if self.embedder is None or not record or record.removed_at or not record.index_pending:
            return
        outcome = index_doc(record.doc_id, storage=self.storage, embedder=self.embedder)
        pending = outcome.status in {"failed", "skipped"}
        self._change(
            record,
            index_pending=pending,
            last_error="index_pending" if pending else None,
            next_attempt_at=self.now() + timedelta(minutes=5) if pending else None,
        )
        if pending:
            logger.warning("meeting.index_pending meeting_id=%s", record.meeting_id)

    def advance(self, meeting_id, *, explicit=False):
        r = self.storage.get_meeting(meeting_id)
        if r is None or r.removed_at:
            return
        if r.persistence_status in {"failed", "inaccessible"} and not explicit:
            return
        now = self.now()
        if r.create_lease_until and r.create_lease_until > now:
            return
        if not explicit and r.next_attempt_at and r.next_attempt_at > now:
            return
        if r.persistence_status == "saved":
            self._index(r)
            return
        if r.attempts >= self.settings.meeting_record_max_attempts and not explicit:
            self._change(
                r, persistence_status="failed", last_error="attempt_limit", failed_at=self.now()
            )
            return
        r = self._change(
            r,
            create_attempt_id=uuid4(),
            create_lease_until=now + timedelta(seconds=self.settings.meeting_doc_create_lease_s),
            persistence_status="creating" if not r.google_document_id else "doc_created",
            attempts=r.attempts + 1,
            next_reconcile_at=now + timedelta(hours=1),
        )
        if r is None:
            return
        creating = not r.google_document_id
        try:
            if creating:
                matches = self.writer.search(r.meeting_id)
                if not self._owns(r):
                    return
                matches = [f for f in matches if f.document_id not in r.google_deletions]
                candidates = sorted(
                    (f for f in matches if not f.trashed),
                    key=lambda f: (f.created_at, f.document_id),
                )
                if candidates:
                    r = self._adopt(r, candidates[0].document_id)
                elif matches:
                    raise WriterError("trashed_matches_require_admin")
                elif not r.pending_payload:
                    raise WriterError("payload_unavailable")
                else:
                    # Every attempt is tagged before Google can see its body.
                    document_id = self.writer.create(
                        meeting_id=r.meeting_id,
                        attempt_id=r.create_attempt_id,
                        voice_channel_id=r.voice_channel_id,
                        title=r.title,
                        html=render_html(r),
                    )
                    r = self._adopt(r, document_id)
                if r is None:
                    return  # late completion: unshared; recurring reconciliation owns cleanup
                creating = False
            if not self._owns(r):
                return
            self.writer.share(r.google_document_id, r.audience_group_emails)
            if not self._owns(r):
                return
            r = self._change(r, persistence_status="shared")
            if r is None or not self._owns(r):
                return
            result = self.writer.fetch(r.google_document_id)
            if not self._owns(r):
                return
            if result.permissions is None:
                raise WriterError("missing_acl")
            resolved = resolve_google_permissions(result.permissions, self.directory)
            # Never mint grants from the requested audience. Only owner-read ACL
            # evidence is allowed; keep the generation-time audience snapshot.
            cataloged = self.storage.catalog_meeting(
                r,
                result,
                resolved.grants,
                expires_at=source_grant_expiry(
                    self.now(), self.settings.source_access_max_age_hours
                ),
                actor="meeting-records",
            )
            if cataloged:
                self._index(self.storage.get_meeting(meeting_id))
        except WriterError as exc:
            if exc.code == "unexpected_acl" and r.google_document_id:
                self.remove(r.meeting_id, actor="security:unexpected_acl")
            else:
                self._failure(r, exc, creating=creating)
        except Exception:
            # Includes catalog/directory failures. The ID and pending state are
            # already durable. Never include exceptions containing private data.
            self._failure(r, WriterError("persistence_unavailable"), creating=creating)
        finally:
            current = self.storage.get_meeting(meeting_id)
            if (
                current
                and r
                and current.create_attempt_id == r.create_attempt_id
                and not current.removed_at
            ):
                # Ambiguous creation retains its lease until reconciliation.
                if current.persistence_status != "create_uncertain":
                    self._change(current, create_lease_until=None)

    def reconcile(self, meeting_id):
        r = self.storage.get_meeting(meeting_id)
        now = self.now()
        if not r or not r.next_reconcile_at or r.next_reconcile_at > now:
            return
        if r.create_lease_until and r.create_lease_until > now:
            return
        r = self._change(
            r,
            create_attempt_id=uuid4(),
            create_lease_until=now + timedelta(seconds=self.settings.meeting_doc_create_lease_s),
        )
        if r is None:
            return
        error = None
        try:
            if r.removed_at:
                r = self.storage.purge_meeting_catalog(meeting_id, [], actor="meeting-reconcile")
            matches = self.writer.search(r.meeting_id)
            ids = {match.document_id for match in matches}
            ids.update(
                document_id
                for document_id, state in r.google_deletions.items()
                if state == "pending"
            )
            if r.removed_at:
                ids.update(r.removed_google_document_ids)
            for document_id in sorted(ids):
                current = self.storage.get_meeting(meeting_id)
                if (
                    current.create_attempt_id != r.create_attempt_id
                    or current.create_lease_until <= self.now()
                ):
                    return
                if (
                    current.removed_at
                    or current.google_deletions.get(document_id) == "pending"
                    or (current.persistence_status == "failed" and not current.google_document_id)
                    or (current.google_document_id and document_id != current.google_document_id)
                ):
                    if current.removed_at:
                        self.storage.purge_meeting_catalog(
                            meeting_id, [document_id], actor="meeting-reconcile"
                        )
                    self._delete(meeting_id, document_id, cleanup_attempt=r.create_attempt_id)
        except Exception:
            error = "reconcile_failed"
            logger.warning("meeting.reconcile_failed meeting_id=%s", meeting_id)
        finally:
            current = self.storage.get_meeting(meeting_id)
            if current and current.create_attempt_id == r.create_attempt_id:
                self._change(
                    current,
                    create_lease_until=None,
                    next_reconcile_at=self.now() + timedelta(hours=1),
                    last_error=error
                    or (None if current.last_error == "reconcile_failed" else current.last_error),
                )

    def _delete(self, meeting_id, document_id, *, cleanup_attempt=None):
        # Fence adoption before the external call: even a timed-out delete can
        # complete after this worker releases its lease. Keep uncertain intents.
        while True:
            current = self.storage.get_meeting(meeting_id)
            if current.google_deletions.get(document_id) == "confirmed" or (
                current.google_document_id == document_id and current.google_deleted_at
            ):
                return
            if cleanup_attempt is not None and (
                current.create_attempt_id != cleanup_attempt
                or not current.create_lease_until
                or current.create_lease_until <= self.now()
            ):
                return
            if document_id in current.google_deletions:
                break
            if (
                self._change(
                    current, google_deletions=current.google_deletions | {document_id: "pending"}
                )
                is not None
            ):
                break
        self.writer.delete(document_id)
        while True:
            current = self.storage.get_meeting(meeting_id)
            values = {"google_deletions": current.google_deletions | {document_id: "confirmed"}}
            if current.google_document_id == document_id and not current.google_deleted_at:
                values["google_deleted_at"] = self.now()
            if self._change(current, **values) is not None:
                return

    def remove(self, meeting_id, *, actor):
        r = self.storage.get_meeting(meeting_id)
        if r is None:
            return None
        if r.persistence_status == "removed" and "pending" not in r.google_deletions.values():
            return self.storage.purge_meeting_catalog(meeting_id, [], actor=actor)
        while not r.removed_at:
            updated = self.storage.change_meeting(
                r,
                {
                    "removed_at": self.now(),
                    "removed_by": actor,
                    "persistence_status": "removing",
                    "create_attempt_id": uuid4(),
                    "create_lease_until": None,
                    "delivery_status": "disabled",
                    "index_pending": False,
                    "pending_payload": None,
                    "next_reconcile_at": self.now(),
                    "title": None,
                    "summary": None,
                    "decisions": [],
                    "action_items": [],
                    "participants": [],
                    "audience_team_ids": [],
                    "audience_group_emails": [],
                    "requester_person_id": None,
                    "requester_discord_id": None,
                    "guild_id": None,
                    "voice_channel_id": None,
                    "started_at": None,
                    "ended_at": None,
                    "generated_at": None,
                },
                actor=actor,
            )
            r = updated if updated is not None else self.storage.get_meeting(meeting_id)
            if r is None:
                return None
        # Purge catalog even if Google is unavailable: retained text must not
        # remain readable while external cleanup is being retried. The canonical
        # URL may have been ingested without ever attaching record.doc_id.
        r = self.storage.purge_meeting_catalog(meeting_id, [], actor=actor)
        try:
            matches = self.writer.search(meeting_id)
            ids = {m.document_id for m in matches}
            r = self.storage.purge_meeting_catalog(meeting_id, sorted(ids), actor=actor)
            ids.update(r.removed_google_document_ids)
            if r.google_document_id and not r.google_deleted_at:
                ids.add(r.google_document_id)
            for file_id in sorted(
                ids, key=lambda file_id: (file_id != r.google_document_id, file_id)
            ):
                self._delete(meeting_id, file_id)
        except Exception:
            r = self.storage.get_meeting(meeting_id)
            self._change(
                r,
                persistence_status="removing",
                last_error="unexpected_acl_removal_pending"
                if r.removed_by == "security:unexpected_acl"
                else "removal_pending",
                next_reconcile_at=self.now() + timedelta(hours=1),
            )
            return self.storage.get_meeting(meeting_id)
        # Content-free tombstone. Retain Discord cleanup identifiers for #223.
        empty = {
            "title": None,
            "summary": None,
            "decisions": [],
            "action_items": [],
            "participants": [],
            "pending_payload": None,
            "audience_team_ids": [],
            "audience_group_emails": [],
            "requester_person_id": None,
            "requester_discord_id": None,
            "guild_id": None,
            "voice_channel_id": None,
            "started_at": None,
            "ended_at": None,
            "generated_at": None,
            "doc_url": None,
            "persistence_status": "removed",
            "last_error": "unexpected_acl" if actor == "security:unexpected_acl" else None,
            "next_reconcile_at": self.now() + timedelta(hours=1),
        }
        return self._change(self.storage.get_meeting(meeting_id), **empty)

    def retry_due(self, limit):
        now = self.now()
        due = []
        for r in self.storage.list_meetings():
            times = [
                t
                for t in (
                    r.next_attempt_at
                    if r.persistence_status not in TERMINAL
                    or (r.persistence_status == "saved" and r.index_pending)
                    else None,
                    r.next_reconcile_at,
                    r.ended_at + timedelta(days=self.settings.meeting_record_retention_days)
                    if r.ended_at and not r.removed_at
                    else None,
                )
                if t is not None
            ]
            if r.persistence_status == "removing":
                times.append(r.next_reconcile_at or now)
            if r.persistence_status == "failed" and r.pending_payload:
                times.append((r.failed_at or r.generated_at) + timedelta(days=7))
            if (
                times
                and min(times) <= now
                and not (r.create_lease_until and r.create_lease_until > now)
            ):
                due.append((min(times), r.meeting_id))
        result = MeetingRetryResult()
        for _, meeting_id in sorted(due)[:limit]:
            r = self.storage.get_meeting(meeting_id)
            phase = "persistence"
            errors = set()
            try:
                if (
                    r.persistence_status == "removing"
                    or (r.removed_at and "pending" in r.google_deletions.values())
                ) or (
                    r.ended_at
                    and not r.removed_at
                    and r.ended_at + timedelta(days=self.settings.meeting_record_retention_days)
                    <= now
                ):
                    phase = "cleanup"
                    self.remove(meeting_id, actor=r.removed_by or "retention")
                elif (
                    r.persistence_status == "failed"
                    and r.pending_payload
                    and (r.failed_at or r.generated_at) + timedelta(days=7) <= now
                ):
                    self._change(r, pending_payload=None)
                phase = "cleanup"
                self.reconcile(meeting_id)
                if self.storage.get_meeting(meeting_id).last_error == "reconcile_failed":
                    errors.add("cleanup")
                current = self.storage.get_meeting(meeting_id)
                phase = "index" if current.persistence_status == "saved" else "persistence"
                self.advance(meeting_id)
            except Exception:
                errors.add(phase)
                logger.warning("meeting.retry_failed meeting_id=%s phase=%s", meeting_id, phase)
            current = self.storage.get_meeting(meeting_id)
            if (
                current.persistence_status == "removing"
                or "pending" in current.google_deletions.values()
            ):
                errors.add("cleanup")
            if not current.removed_at:
                if current.persistence_status != "saved":
                    errors.add("persistence")
                elif current.index_pending:
                    errors.add("index")
            result.attempted += 1
            result.failed += bool(errors)
            result.succeeded += not errors
            result.persistence_failed += "persistence" in errors
            result.index_failed += "index" in errors
            result.cleanup_failed += "cleanup" in errors
        return result
